    /** L'icône d'une entrée, ou un rond neutre si la rubrique est inconnue. */
    public static function pour(array $item): string
    {
        if (!empty($item['icon'])) {
            return (string) $item['icon'];
        }
        if (isset($item['tab'])) {
            return self::PAR_ONGLET[$item['tab']] ?? 'circle';
        }
        $adresse = rtrim(explode('#', (string) ($item['href'] ?? ''))[0], '/');
        return self::PAR_ADRESSE[$adresse === '' ? '/' : $adresse] ?? 'circle';
    }
